//! `tl_writer_rust` part 1 (S09): emits the Rust data model of a scheme —
//! one struct per constructor, one enum per multi-constructor type, one
//! struct per function plus the `Function` umbrella enum — with serde
//! derives. tdlib's JSON writes the TL field names verbatim and tags every
//! object with its constructor name under `@type`, so field names carry no
//! serde renaming and variants get explicit `@type` renames.

use tdtl::TlProgram;

use crate::model::{FieldType, SchemeModel, TypeKind};

/// Rust keywords and reserved words that cannot appear as plain identifiers.
/// tl field names in td_api avoid them; anything else becomes `r#name`.
fn is_keyword(name: &str) -> bool {
    const KEYWORDS: &[&str] = &[
        "as", "async", "await", "box", "break", "const", "continue", "crate", "dyn", "else",
        "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod",
        "move", "mut", "pub", "ref", "return", "static", "struct", "super", "trait", "true", "try",
        "type", "unsafe", "use", "where", "while", "yield",
    ];
    KEYWORDS.contains(&name)
}

/// `messageText` → `MessageText` (constructor ids are camelCase).
fn capitalize(name: &str) -> String {
    let mut chars = name.chars();
    match chars.next() {
        Some(c) => c.to_uppercase().collect::<String>() + chars.as_str(),
        None => String::new(),
    }
}

fn field_ident(name: &str) -> String {
    if is_keyword(name) {
        format!("r#{name}")
    } else {
        name.to_owned()
    }
}

/// Renders the whole generated module for a scheme.
pub fn write_rust(p: &TlProgram, m: &SchemeModel, umbrella: &str, source: &str) -> String {
    let mut out = String::with_capacity(4 << 20);
    out.push_str("// @generated by tl-codegen — DO NOT EDIT.\n");
    out.push_str(&format!("// Source: {source}\n\n"));
    out.push_str("use serde::{Deserialize, Serialize};\n\n");

    let mut emitted_names = std::collections::BTreeSet::new();

    for &tid in p.type_ids.values() {
        match &m.type_kinds[tid] {
            TypeKind::Prim(_) | TypeKind::Vector => {}
            TypeKind::Struct { ctor } => {
                let name = &p.types[tid].id;
                emit_struct(&mut out, p, m, *ctor, name);
                emitted_names.insert(name.clone());
            }
            TypeKind::Enum { ctors } => {
                // The `#`/`Type` meta types classify as empty enums and are
                // never emitted.
                if ctors.is_empty() {
                    continue;
                }
                // Structs for every constructor, then the umbrella enum.
                for &c in ctors {
                    let name = capitalize(&p.ctors[c].id);
                    emit_struct(&mut out, p, m, c, &name);
                    assert!(
                        emitted_names.insert(name.clone()),
                        "duplicate Rust struct name {name}"
                    );
                }
                emit_enum(&mut out, p, ctors, &p.types[tid].id);
                assert!(
                    emitted_names.insert(p.types[tid].id.clone()),
                    "enum name {} collides with a struct",
                    p.types[tid].id
                );
            }
        }
    }

    // Functions: structs plus the `Function` umbrella enum (td's base
    // function class).
    for &f in &m.functions {
        let name = capitalize(&p.ctors[f].id);
        emit_struct(&mut out, p, m, f, &name);
        assert!(
            emitted_names.insert(name.clone()),
            "function struct name {name} collides"
        );
    }
    emit_enum(&mut out, p, &m.functions, umbrella);

    out.push_str(&format!(
        "pub const SCHEME_TYPES: usize = {};\npub const SCHEME_CTORS: usize = {};\n\
         pub const SCHEME_FUNCTIONS: usize = {};\n",
        p.total_types, p.total_ctors, p.total_funcs
    ));
    let enums = m
        .type_kinds
        .iter()
        .filter(|k| matches!(k, TypeKind::Enum { ctors } if !ctors.is_empty()))
        .count();
    let struct_kinds = m
        .type_kinds
        .iter()
        .filter(|k| matches!(k, TypeKind::Struct { .. }))
        .count();
    let enum_ctors: usize = m
        .type_kinds
        .iter()
        .map(|k| match k {
            TypeKind::Enum { ctors } => ctors.len(),
            _ => 0,
        })
        .sum();
    // Every non-builtin ctor (total_ctors - 9) and every function get a
    // struct; multi-ctor types additionally get an enum.
    let structs = struct_kinds + enum_ctors + p.total_funcs;
    assert_eq!(
        struct_kinds + enum_ctors,
        p.total_ctors - BUILTIN_CTORS,
        "ctor accounting"
    );
    out.push_str(&format!(
        "pub const GENERATED_STRUCTS: usize = {structs};\n\
         pub const GENERATED_ENUMS: usize = {enums};\n"
    ));
    out
}

/// Constructors of built-in simple types (double, string, int32, int53,
/// int64, bytes, boolFalse, boolTrue, vector) — no Rust structs for these.
const BUILTIN_CTORS: usize = 9;

fn emit_struct(out: &mut String, p: &TlProgram, m: &SchemeModel, c: usize, name: &str) {
    out.push_str("#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]\n");
    out.push_str(&format!("#[serde(rename = \"{}\")]\n", p.ctors[c].id));
    let fields = &m.ctor_fields[c];
    if fields.is_empty() {
        out.push_str(&format!("pub struct {name};\n\n"));
        return;
    }
    out.push_str(&format!("pub struct {name} {{\n"));
    for f in fields {
        out.push_str(&format!(
            "    pub {}: {},\n",
            field_ident(&f.name),
            rust_field_type(p, m, &f.ty)
        ));
    }
    out.push_str("}\n\n");
}

fn emit_enum(out: &mut String, p: &TlProgram, ctors: &[usize], name: &str) {
    out.push_str("#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]\n");
    out.push_str("#[serde(tag = \"@type\")]\n");
    out.push_str(&format!("pub enum {name} {{\n"));
    for &c in ctors {
        out.push_str(&format!(
            "    #[serde(rename = \"{}\")]\n    {}({}),\n",
            p.ctors[c].id,
            capitalize(&p.ctors[c].id),
            capitalize(&p.ctors[c].id)
        ));
    }
    out.push_str("}\n\n");
}

fn rust_field_type(p: &TlProgram, m: &SchemeModel, ty: &FieldType) -> String {
    match ty {
        FieldType::Prim(prim) => prim.rust_type().to_owned(),
        FieldType::Vector(inner) => format!("Vec<{}>", rust_field_type(p, m, inner)),
        FieldType::Boxed(t) | FieldType::Bare(t) => {
            let name = m.type_name(p, *t);
            if m.cyclic[*t] {
                format!("Box<{name}>")
            } else {
                name
            }
        }
    }
}
